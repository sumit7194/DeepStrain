"""Silent-f32 check of the L128 C12 gate (registered in reports/stepT_runnotes.md, 2026-11-28 10:17-10:30 entry,
BEFORE any computation): does a float32 box output that PASSES the 3e-4 closure gate ever carry a wrong template / lag
selection? Each sampled box and kind is recomputed in float64 on the CPU, from the same inputs, by the driver's own
code (chunk(), Box, Fine, score_kind, box_record under the _PREC switch that c12_float64 uses), and compared with the
stored output.

Never writes production files: refs and snippet files are regenerated by coh2t_drive.chunk() into a scratch state
dir (plan.json, grids/, kern/ symlinked read-only), and all output goes to results/coh2t/c12_silent/.

  python benchmark/coh2t_c12_silent.py controls   # must-pass identity (box 23 dec_sg, 1452 bg) + must-fail (box 23)
  python benchmark/coh2t_c12_silent.py main       # 20 fg + 10 bg
  python benchmark/coh2t_c12_silent.py decsg      # 20 dec_sg (after the decoys step has finished)
  python benchmark/coh2t_c12_silent.py summary
  python benchmark/coh2t_c12_silent.py decsg_all  # the Bridge's GO (2026-11-28): every dec_sg box in float64, the f64
                                                  # result under the final name, every f32 output kept in L128_c12/
"""
import os
for _v in ("OMP_NUM_THREADS", "VECLIB_MAXIMUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS"):
    os.environ[_v] = os.environ.get("C12S_THREADS", "1")   # 1 = as the queue's children (production's float64 path)
import json
import sys
import time
from pathlib import Path

import numpy as np

B = Path(__file__).resolve().parent
sys.path.insert(0, str(B))
import coh2t_drive as D  # noqa: E402

L = D.L
L_MAX = 128
PROD = D.out_dir(L_MAX)                                   # COH2T_OUTDIR redirects it (the tests run on copies)
CAL = D.OUT / f"L{L_MAX}" / "decoy_calibration.json"
SCR = Path(os.environ["C12S_SCR"]) if os.environ.get("C12S_SCR") else D.OUT / "c12_silent"
ST = SCR / "state"
RES = SCR / "results.jsonl"
SEED0 = 20261128
SAMPLE = {"fg": (1, 20), "bg": (2, 10), "dec_sg": (3, 20)}      # kind: (seed offset j, n)
REL_TOL, F64_CLOSURE_FLAG = 1e-3, 1.5e-4
STATS = ("H_rho", "L_rho", "H_chi2", "L_chi2")


def scratch_state():
    ST.mkdir(parents=True, exist_ok=True)
    for name in ("plan.json", "grids", "kern"):
        lnk = ST / name
        if not lnk.exists():
            lnk.symlink_to(D.STATE / name)
    (ST / "chunk").mkdir(exist_ok=True)
    assert D.STATE.resolve() != ST.resolve()
    D.STATE = ST                                          # chunk(), extra_files(), grid() now resolve here


PL = None
SIGN = json.loads((L.OUT / "E1_phase_model.json").read_text())["sign"]
TARGET = json.loads(CAL.read_text())["target_plain"]
_cache = {}


def series(det, gps):
    if (det, gps) not in _cache:
        if len(_cache) >= 4:
            _cache.clear()
        _cache[(det, gps)] = L.load_ww(det, gps)
    return _cache[(det, gps)]


def load_npz(path):
    z = np.load(path, allow_pickle=False)
    return json.loads(str(z["meta"])), {k: z[k] for k in z.files if k != "meta"}


def cands(tid, kind):
    return [c for c in PL["candidates"] if c["valid"] and c["tid"] == tid and c["kind"] == kind]


def recompute_f64(tid, kind, meta_ref):
    """The float64 box result, exactly as c12_float64 computes it, from scratch-regenerated inputs."""
    cs = cands(tid, kind)
    assert [{k: c.get(k) for k in D.META} for c in cs] == meta_ref["candidates"], \
        f"box {tid} {kind}: plan candidates differ from the stored record"
    assert (D.STATE / "grids" / f"L{L_MAX}_tid{tid:04d}.npz").exists(), f"grid of box {tid} missing (would be written)"
    target = TARGET if kind in D.DECOYS else None          # run(): target only in the decoys step
    t0 = time.time()
    D.chunk(L_MAX, [tid], [kind])
    refs = D.STATE / "chunk" / f"refs_L{L_MAX}_tid{tid:04d}.npy"
    old = dict(D._PREC)
    D._PREC.update(r=np.float64, c=np.complex128)
    try:
        eng = L.Engine("cpu", 4.0, 1, cdt=np.complex128, rdt=np.float64)
        box = D.Box(tid, L_MAX, "cpu", eng, SIGN, np.load(refs))
        res = D.score_kind(box, D.Fine("cpu"), series, cs, kind, target, L_MAX)
        meta, arrs = D.box_record(box, tid, L_MAX, kind, cs, res, t0)
    finally:
        D._PREC.clear(); D._PREC.update(old)
    for f in [refs] + [f for c in cs for f in D.extra_files(c).values()]:
        f.unlink(missing_ok=True)
    return meta, arrs, round(time.time() - t0, 1)


def compare(a32, a64):
    same = all(np.array_equal(a32[k], a64[k]) for k in ("tmpl", "lag") if k in a32)
    rel = {}
    for k in STATS:
        if k in a32 and a32[k].shape == a64[k].shape:
            a, b = a32[k].astype(np.float64), a64[k].astype(np.float64)
            rel[k] = float(np.max(np.abs(a - b) / np.maximum(np.abs(b), 1.0))) if a.size else 0.0
    return same, rel


def record(row, path=None):
    SCR.mkdir(parents=True, exist_ok=True)
    with (path or RES).open("a") as f:
        f.write(json.dumps(row) + "\n")
    print(json.dumps(row), flush=True)


def done_rows(path=None):
    path = path or RES
    return [json.loads(l) for l in path.read_text().splitlines()] if path.exists() else []


DECSG = SCR / "decsg_all.jsonl"
WHY = "decsg_all: the Bridge's GO 2026-11-28 ~10:40 IST after decoy rule (b) tripped (dec_sg breach rate 25/61)"


def same_arrays(a, b):
    return set(a) == set(b) and all(np.array_equal(a[k], b[k]) for k in a)


def decsg_all():
    """Every dec_sg box with candidates, in tid order, resumable (DECSG rows). Already-arbitrated boxes (final = f64)
    are re-verified: the recompute must reproduce the stored f64 result. The others: the stored f32 output is copied
    to L128_c12/ (and the copy verified) BEFORE the f64 result replaces the final name (os.replace). Sticky gate as
    C12a: float64 above CLOSURE_MAX writes the f64 breach record and C12_STOP, removes the final file, and stops."""
    c12d = D.c12_dir(L_MAX)
    c12d.mkdir(parents=True, exist_ok=True)
    assert not D.c12_stop_file(L_MAX).exists(), "C12_STOP exists: no recompute until it is ruled on"
    pop = sorted({c["tid"] for c in PL["candidates"] if c["valid"] and c["kind"] == "dec_sg"})
    if os.environ.get("C12S_BOXES"):                          # tests only: an explicit list of tids
        pop = [t for t in pop if t in {int(v) for v in os.environ["C12S_BOXES"].split(",")}]
    if os.environ.get("C12S_TEST_CLOSURE_MAX"):               # tests only: force a float64 'breach'
        D.CLOSURE_MAX = float(os.environ["C12S_TEST_CLOSURE_MAX"])
    missing = [t for t in pop if not (PROD / f"box_{t:04d}_dec_sg.npz").exists()]
    assert not missing, f"decoys step not finished: {len(missing)} dec_sg boxes not done"
    have = {r["tid"] for r in done_rows(DECSG)}
    for tid in pop:
        if tid in have:
            continue
        out, rec_path = PROD / f"box_{tid:04d}_dec_sg.npz", c12d / f"box_{tid:04d}_dec_sg_f32.npz"
        meta_st, arrs_st = load_npz(out)
        meta64, arrs64, sec = recompute_f64(tid, "dec_sg", meta_st)
        c64 = meta64.get("closure_max", 0.0)
        if meta_st.get("c12", {}).get("reason", "").startswith("decsg_all"):
            raise SystemExit(f"box {tid}: already rewritten by decsg_all but has no row in {DECSG}; inspect by hand")
        if "c12" in meta_st:                                   # arbitrated in-run: final holds float64; re-verify
            ident = same_arrays(arrs_st, arrs64)
            meta32, arrs32 = load_npz(rec_path)
            same, rel = compare(arrs32, arrs64)
            row = dict(tid=tid, prior="arbitrated_in_run", f64_reproduces_stored=bool(ident), same_selection=bool(same),
                       max_rel=rel, closure_f32=meta32.get("closure_max", 0.0), closure_f64=c64, seconds=sec)
            record(row, DECSG)
            assert ident, f"box {tid}: the f64 recompute does not reproduce the stored f64 result"
            continue
        meta32, arrs32 = meta_st, arrs_st
        same, rel = compare(arrs32, arrs64)
        if rec_path.exists():                                  # a restart after the copy, before the replace
            mz, az = load_npz(rec_path)
            assert same_arrays(az, arrs32) and mz == meta32, f"{rec_path} exists and differs from {out}"
        else:
            D.write_box(rec_path, meta32, arrs32)
            mz, az = load_npz(rec_path)
            assert same_arrays(az, arrs32) and mz == meta32, f"{rec_path} does not reproduce {out}"
        rec = dict(arbitrated=True, reason=WHY, closure_f32=meta32.get("closure_max", 0.0), closure_f64=c64,
                   cleared=bool(c64 <= D.CLOSURE_MAX), same_template_and_lag_selection=bool(same), f32_vs_f64=rel,
                   f32_record=str(rec_path), f64_seconds=sec, precision="float64 (CPU)")
        row = dict(tid=tid, prior="f32", same_selection=bool(same), max_rel=rel, closure_f32=rec["closure_f32"],
                   closure_f64=c64, seconds=sec)
        if c64 > D.CLOSURE_MAX:
            D.write_box(c12d / f"box_{tid:04d}_dec_sg_f64_breach.npz", dict(meta64, c12=rec), arrs64)
            D.c12_stop_file(L_MAX).write_text(json.dumps(dict(tid=tid, kind="dec_sg", **rec), indent=1))
            out.unlink()
            record(dict(row, f64_breach=True), DECSG)
            raise SystemExit(f"C12 float64 BREACH in box {tid} dec_sg ({c64:.3e}); C12_STOP written; stopping")
        meta64["c12"] = rec
        D.write_box(out, meta64, arrs64)
        record(row, DECSG)
    rows = done_rows(DECSG)
    f32rows = [r for r in rows if r["prior"] == "f32"]
    res = dict(n_boxes=len(rows), n_reverified=len(rows) - len(f32rows),
               reverified_all_reproduce=all(r["f64_reproduces_stored"] for r in rows if r["prior"] != "f32"),
               n_nonbreaching_f32=len(f32rows),
               nonbreaching_selection_changes=sum(not r["same_selection"] for r in f32rows),
               nonbreaching_max_rel=max((max(r["max_rel"].values(), default=0.0) for r in f32rows), default=0.0),
               max_closure_f64=max(r["closure_f64"] for r in rows))
    (SCR / "decsg_all_summary.json").write_text(json.dumps(res, indent=1))
    print(json.dumps(res, indent=1), flush=True)


def controls():
    out = {}
    for tid, kind in ((23, "dec_sg"), (1452, "bg")):
        meta_st, arrs_st = load_npz(PROD / f"box_{tid:04d}_{kind}.npz")
        assert "c12" in meta_st, f"box {tid} {kind} is not a float64-arbitrated result"
        meta64, arrs64, sec = recompute_f64(tid, kind, meta_st)
        ident = set(arrs_st) == set(arrs64) and all(np.array_equal(arrs_st[k], arrs64[k]) for k in arrs_st)
        out[f"identity_{tid}_{kind}"] = ident
        record(dict(role="control_identity", tid=tid, kind=kind, identical=bool(ident), seconds=sec,
                    closure_f64=meta64.get("closure_max", 0.0)))
        if (tid, kind) == (23, "dec_sg"):
            _, arrs32 = load_npz(D.OUT / f"L{L_MAX}_c12" / "box_0023_dec_sg_f32.npz")
            same, rel = compare(arrs32, arrs64)
            out["mustfail_23_selection_differs"] = not same
            record(dict(role="control_mustfail", tid=tid, kind=kind, same_selection=bool(same), max_rel=rel,
                        detected=bool(not same)))
    ok = all(out.values())
    record(dict(role="controls_verdict", **{k: bool(v) for k, v in out.items()}, pass_=bool(ok)))
    assert ok, f"controls FAILED: {out}; the check is void"


def sample(kind):
    j, n = SAMPLE[kind]
    pop = sorted({c["tid"] for c in PL["candidates"] if c["valid"] and c["kind"] == kind})
    order = np.random.default_rng(SEED0 + j).permutation(pop)
    take, skipped = [], []
    for tid in map(int, order):
        p = PROD / f"box_{tid:04d}_{kind}.npz"
        if not p.exists():
            skipped.append((tid, "not done"))
            continue
        if "c12" in load_npz(p)[0]:
            skipped.append((tid, "arbitrated"))
            continue
        take.append(tid)
        if len(take) == n:
            break
    return take, skipped, len(pop)


def run_kind(kind):
    have = {(r["tid"], r["kind"]) for r in done_rows() if r.get("role") == "sample"}
    take, skipped, npop = sample(kind)
    record(dict(role="sample_drawn", kind=kind, seed=SEED0 + SAMPLE[kind][0], population=npop, take=take,
                skipped=skipped))
    for tid in take:
        if (tid, kind) in have:
            continue
        meta_st, arrs_st = load_npz(PROD / f"box_{tid:04d}_{kind}.npz")
        meta64, arrs64, sec = recompute_f64(tid, kind, meta_st)
        same, rel = compare(arrs_st, arrs64)
        c64 = meta64.get("closure_max", 0.0)
        record(dict(role="sample", tid=tid, kind=kind, n_cand=len(meta_st["candidates"]), same_selection=bool(same),
                    max_rel=rel, rel_ok=bool(max(rel.values(), default=0.0) <= REL_TOL),
                    closure_f32=meta_st.get("closure_max", 0.0), closure_f64=c64,
                    f64_closure_ok=bool(c64 <= F64_CLOSURE_FLAG), seconds=sec))
        if not same:
            print(f"!! SELECTION DIFFERS in box {tid} {kind}: registered action applies", flush=True)


def summary():
    rows = [r for r in done_rows() if r.get("role") == "sample"]
    out = {}
    for kind in SAMPLE:
        rs = [r for r in rows if r["kind"] == kind]
        if not rs:
            continue
        n, nd = len(rs), sum(not r["same_selection"] for r in rs)
        out[kind] = dict(n=n, selection_changes=nd, rate_ub95=(3.0 / n if nd == 0 else None),
                         rel_fail=sum(not r["rel_ok"] for r in rs),
                         max_rel=max(max(r["max_rel"].values(), default=0.0) for r in rs),
                         f64_closure_fail=sum(not r["f64_closure_ok"] for r in rs),
                         max_closure_f32=max(r["closure_f32"] for r in rs))
    ctl = [r for r in done_rows() if r.get("role") == "controls_verdict"]
    res = dict(controls=ctl[-1] if ctl else None, by_kind=out, env=L.stamp() if hasattr(L, "stamp") else None)
    (SCR / "summary.json").write_text(json.dumps(res, indent=1, default=str))
    print(json.dumps(res, indent=1, default=str))


